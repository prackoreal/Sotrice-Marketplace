"""city-roads — publishes the routable road graph as the legacy `road_network`
attribute for everything that already consumes it (agent-behavior-test uses
it for pathfinding, transit-sim finds its rail lines in it, rendering draws
it, economics measures building/road distances).

The data is now REAL OpenStreetMap data for whichever area is active (see
city_data.py and docs/city-schema/schema.md): this plugin reads the very
same cached dataset city-data publishes, converts the graph to today's
`road_network` shape (nodes keyed by OSM id with x/z/lat/lon, directed edges
with from/to/length_m/name/highway — plus the new optional fields lanes,
width_m, oneway, maxspeed_kmh, layer, tunnel, bridge, mode), merges the REAL
rail/subway/tram graph in, and follows live area changes (`city_dataset`
with a new area id => the new graph is republished, no restart).

Fallback: if the active area has no cached dataset (offline first run) the
original hand-extracted demo files in city_roads_data/ are used, plus —
only there, and only when `custom_underground` is set in active_area.json —
the clearly-labelled SYNTHETIC underground layer. Real areas never get it.

Sandbox mode (building moved in the editor): the local road network around
it is regenerated by road_regen.py; the persisted overlay is per area, so
switching areas never mixes edits.

Data: (c) OpenStreetMap contributors, ODbL — republished as `road_attribution`.
Registered in plugins/registry.json as "city-roads".
"""

import json
import os
import threading
import time

import citydata_store as store
import road_regen
from sotrice_client import World

DATA_DIR = store.LEGACY_DIR
DEFAULT_AREA = store.DEFAULT_AREA


def active_area() -> str:
    return store.read_active()["area"]


def _legacy_file(area: str) -> str:
    return os.path.join(DATA_DIR, f"{area}.json")


def load_area(area: str):
    """-> (road_data, extra_data, meta) for `area`, or None if neither a cached
    dataset nor a legacy demo extract exists yet. `road_data` is the mutable
    street graph road_regen edits; `extra_data` (rail / custom underground) is
    merged in only at publish time."""
    ds = store.load_dataset(area)
    if ds is not None:
        net = store.legacy_road_network(ds)
        street_nodes = set(ds["graph"]["nodes"])
        road = {"nodes": {k: v for k, v in net["nodes"].items() if k in street_nodes},
                "edges": [e for e in net["edges"] if e.get("mode") in ("road", "foot")]}
        extra = {"nodes": {k: v for k, v in net["nodes"].items() if k not in street_nodes},
                 "edges": [e for e in net["edges"] if e.get("mode") not in ("road", "foot")]}
        meta = {"attribution": ds["area"]["attribution"], "license": ds["area"]["license"],
                "area_description": f"{ds['area']['name']} — real OpenStreetMap data", "real": True}
        return road, extra, meta
    path = _legacy_file(area)
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    extra = {"nodes": {}, "edges": []}
    if store.read_active().get("custom_underground"):
        upath = os.path.join(DATA_DIR, f"{area}_underground.json")
        if os.path.exists(upath):
            with open(upath, encoding="utf-8") as f:
                extra = json.load(f)
    meta = {"attribution": data["attribution"], "license": data["license"], "area_description": data["area_description"] + " (small demo extract)", "real": False}
    return {"nodes": data["nodes"], "edges": data["edges"]}, extra, meta


def legacy_overlay_path(area: str) -> str:
    return os.path.join(DATA_DIR, f"{area}_roads_overlay.json")


def load_roads_overlay(area: str) -> dict:
    """Sandbox road regenerations, replayed in order over the extract at load
    time (the extract itself is never mutated)."""
    return store.load_overlay(area, "roads", legacy_overlay_path(area), {"regenerations": []})


def save_roads_overlay(area: str, overlay: dict) -> None:
    store.save_overlay(area, "roads", overlay)


class RoadPublisher:
    def __init__(self, world: World, name: str):
        self.world = world
        self.name = name
        self.control = world.create_entity()
        self.area = None
        self.road = {"nodes": {}, "edges": []}
        self.extra = {"nodes": {}, "edges": []}
        self.overlay = {"regenerations": []}
        self.last_footprint_by_entity: dict = {}
        self.lock = threading.Lock()

    def published(self) -> dict:
        # Extra (rail / custom underground) nodes+edges are merged here, never
        # into the street graph road_regen edits: regen only looks at x/z, and
        # a rail node under a moved building must not count as blocking a road.
        nodes = dict(self.road["nodes"])
        nodes.update(self.extra["nodes"])
        return {"nodes": nodes, "edges": list(self.road["edges"]) + list(self.extra["edges"])}

    def load(self, area: str) -> bool:
        loaded = load_area(area)
        if loaded is None:
            return False
        with self.lock:
            road, extra, meta = loaded
            self.area, self.road, self.extra = area, road, extra
            self.overlay = load_roads_overlay(area)
            for record in self.overlay["regenerations"]:
                road_regen.apply_regeneration(self.road["nodes"], self.road["edges"], record)
            self.last_footprint_by_entity = {}
            self.world.set_many([
                (self.control, "road_network", self.published()),
                (self.control, "road_attribution", meta["attribution"]),
                (self.control, "road_area_description", meta["area_description"]),
            ])
            print(f"[{self.name}] {meta['area_description']} — {len(self.road['nodes'])} street nodes, {len(self.road['edges'])} street edges, "
                  f"{len(self.extra['edges'])} rail/underground edges ({meta['attribution']}); replayed {len(self.overlay['regenerations'])} sandbox regeneration(s)")
        return True

    def on_dataset(self, entity, attribute, value, source):
        if not isinstance(value, dict) or value.get("status") != "ready":
            return
        area = (value.get("area") or {}).get("id")
        if area and area != self.area:
            self.load(area)

    def on_building_footprint(self, entity, attribute, value, source):
        """A building's footprint genuinely CHANGED (drag move relayed by
        city_buildings.py): regenerate the local roads around it. First sight
        of a footprint (pristine or already-regenerated) does nothing, which
        makes replay-on-subscribe and restarts idempotent."""
        if not isinstance(value, list) or len(value) < 3:
            return
        points = [(p["x"], p["z"]) for p in value]
        with self.lock:
            previous = self.last_footprint_by_entity.get(entity)
            self.last_footprint_by_entity[entity] = points
            if previous is None or previous == points or self.area is None:
                return
            record = road_regen.regenerate_around_building(self.road["nodes"], self.road["edges"], points, f"e{entity}")
            road_regen.apply_regeneration(self.road["nodes"], self.road["edges"], record)
            self.overlay["regenerations"].append(record)
            save_roads_overlay(self.area, self.overlay)
            self.world.set_attribute(self.control, "road_network", self.published())
            print(f"[{self.name}] regenerated local roads around moved building (entity {entity}): "
                  f"-{len(record['removed_node_ids'])} node(s), +{len(record['added_nodes'])} synthetic bypass node(s)")


def main():
    with World() as world:
        name = world.identify("city-roads")
        pub = RoadPublisher(world, name)
        world.subscribe("city_dataset", pub.on_dataset, replay=True)
        world.subscribe("building_footprint", pub.on_building_footprint, replay=True)
        area = active_area()
        if not pub.load(area):
            print(f"[{name}] no data for area {area!r} yet - waiting for city-data to download it (city_dataset)")
        try:
            while True:
                time.sleep(3600)
        except KeyboardInterrupt:
            print(f"[{name}] stopped")


if __name__ == "__main__":
    main()
