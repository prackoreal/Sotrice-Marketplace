"""Generates a fully SYNTHETIC (invented, not OpenStreetMap-sourced)
underground transit/tunnel layer for a city-roads area, from a small
hand-authored config (`clients/python/city_roads_data/underground_config.json`).

Klosterneuburg's real OSM extract has no subway at all -- it's too small
a town -- so there is no real data to pull here. This script exists so
rendering-test-ui's Grid view (and anything else that cares about
underground vs. surface infrastructure) has real underground geometry to
render, built the same way city-roads already treats real data: a
static, versioned file generated by a script and checked into the repo,
not invented at runtime. See `scripts/extract_city_roads.py` for the
real-data equivalent of this pipeline -- same shape, synthetic source.

Output: `clients/python/city_roads_data/<area>_underground.json`, a
`{"nodes": {...}, "edges": [...]}` graph in EXACTLY the same node/edge
shape city-roads' real extract already uses (x/z local meters, lat/lon,
length_m/name/highway on edges) plus two new fields that mark this data
as what it is:
  - every node/edge gets `"synthetic": true`
  - every node/edge gets `"layer": "surface"` or `""underground"` (a
    node sitting at y=0 -- a tunnel portal/entrance -- is "surface" even
    though it's part of an otherwise-underground path; everything below
    ground level is "underground")
Underground nodes also carry a real `"y"` (meters, negative = below
ground) -- the real OSM extract's nodes have no `y` at all (implicitly
0, ground level), so this is purely additive, nothing existing changes
shape.

This file is merged into the published `road_network` attribute
alongside (not into) the real extract's own node/edge dicts -- see
city_roads.py's `published_road_network()` -- specifically kept OUT of
the mutable graph road_regen.py's sandbox-mode regeneration operates on,
since that logic only looks at x/z and would otherwise treat a
deep-underground node as a surface obstacle whenever a building happens
to be dragged over the same x/z spot.
"""

import json
import math
import os

DATA_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "clients", "python", "city_roads_data")
CONFIG_PATH = os.path.join(DATA_DIR, "underground_config.json")


def meters_to_latlon(x: float, z: float, origin_lat: float, origin_lon: float):
    """Inverse of extract_city_roads.py's own local-tangent-plane
    projection -- same constants, so synthetic lat/lon stays consistent
    with the real extract's coordinate frame even though these points
    were never actually surveyed."""
    meters_per_deg_lat = 111320.0
    meters_per_deg_lon = 111320.0 * math.cos(math.radians(origin_lat))
    lat = origin_lat + z / meters_per_deg_lat
    lon = origin_lon + x / meters_per_deg_lon
    return lat, lon


def _node(node_id, x, z, y, origin_lat, origin_lon, label=None):
    lat, lon = meters_to_latlon(x, z, origin_lat, origin_lon)
    return {
        "x": x,
        "z": z,
        "y": y,
        "lat": lat,
        "lon": lon,
        "layer": "surface" if y == 0 else "underground",
        "synthetic": True,
        **({"label": label} if label else {}),
    }


def _edge(from_id, to_id, from_node, to_node, name, transport_mode, highway):
    dx = from_node["x"] - to_node["x"]
    dz = from_node["z"] - to_node["z"]
    length_m = round(math.hypot(dx, dz), 2)
    underground = from_node["layer"] == "underground" or to_node["layer"] == "underground"
    return {
        "from": from_id,
        "to": to_id,
        "length_m": length_m,
        "name": name,
        "highway": highway,
        "transport_mode": transport_mode,
        "layer": "underground" if underground else "surface",
        "synthetic": True,
    }


def build_subway_line(line: dict, origin_lat: float, origin_lon: float, nodes: dict, edges: list):
    depth = -abs(line["depth_m"])
    station_ids = []
    for station in line["stations"]:
        node = _node(station["id"], station["x"], station["z"], depth, origin_lat, origin_lon, station.get("label"))
        nodes[station["id"]] = node
        station_ids.append(station["id"])
    for a, b in zip(station_ids, station_ids[1:]):
        edges.append(_edge(a, b, nodes[a], nodes[b], line["name"], "subway", "subway"))
        edges.append(_edge(b, a, nodes[b], nodes[a], line["name"], "subway", "subway"))


def build_car_tunnel(tunnel: dict, origin_lat: float, origin_lon: float, nodes: dict, edges: list):
    """The first and last path point are left at y=0 (a real tunnel
    portal/entrance, still physically at ground level); every interior
    point sits at the configured full depth -- so the tunnel visibly
    dips below ground and comes back up rather than floating at a flat
    depth with no transition at either end."""
    path = tunnel["path"]
    depth = -abs(tunnel["depth_m"])
    n = len(path)
    ids = []
    for i, point in enumerate(path):
        y = 0.0 if i in (0, n - 1) else depth
        nodes[point["id"]] = _node(point["id"], point["x"], point["z"], y, origin_lat, origin_lon)
        ids.append(point["id"])
    for a, b in zip(ids, ids[1:]):
        edges.append(_edge(a, b, nodes[a], nodes[b], tunnel["name"], "car", "service"))
        edges.append(_edge(b, a, nodes[b], nodes[a], tunnel["name"], "car", "service"))


def generate(area_data_path: str, config: dict) -> dict:
    with open(area_data_path, encoding="utf-8") as f:
        area_data = json.load(f)
    origin_lat, origin_lon = area_data["origin_lat"], area_data["origin_lon"]

    nodes: dict = {}
    edges: list = []
    for line in config.get("subway_lines", []):
        build_subway_line(line, origin_lat, origin_lon, nodes, edges)
    for tunnel in config.get("car_tunnels", []):
        build_car_tunnel(tunnel, origin_lat, origin_lon, nodes, edges)
    return {"nodes": nodes, "edges": edges, "source": "synthetic (generated, not from OpenStreetMap)"}


def main():
    with open(CONFIG_PATH, encoding="utf-8") as f:
        config = json.load(f)
    area = config["area"]
    area_data_path = os.path.join(DATA_DIR, f"{area}.json")
    output_path = os.path.join(DATA_DIR, f"{area}_underground.json")

    result = generate(area_data_path, config)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2)
    station_count = sum(len(line["stations"]) for line in config.get("subway_lines", []))
    tunnel_count = len(config.get("car_tunnels", []))
    print(
        f"wrote {output_path}: {len(result['nodes'])} nodes, {len(result['edges'])} directed edges "
        f"({station_count} synthetic subway station(s), {tunnel_count} synthetic car tunnel(s))"
    )


if __name__ == "__main__":
    main()
